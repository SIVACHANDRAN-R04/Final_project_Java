public class Printing_Formate {
    public static void main(String[] args) {

        System.out.printf("%-10s %-5s %-10s%n", "Name", "Age", "City");

        System.out.printf("%-10s %-5d %-10s%n", "Siva", 22, "Salem");
        System.out.printf("%-10s %-5d %-10s%n", "Arun", 23, "Chennai");
        System.out.printf("%-10s %-5d %-10s%n", "Kumar", 21, "Madurai");
    }
}
